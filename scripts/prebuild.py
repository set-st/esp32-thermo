# PlatformIO pre-build script: firmware version and embedded update public key.
# FW_VERSION comes from $FW_VERSION or `git describe`:
#   tag v1.2.0            -> "1.2.0"
#   3 commits after tag   -> "1.2.0-3-gabc1234"
#   no tags yet           -> "0.0.0-gabc1234"
#   uncommitted changes   -> "...-dirty"
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)


def git_version():
    try:
        out = subprocess.check_output(
            ["git", "describe", "--tags", "--match", "v[0-9]*", "--always", "--dirty"],
            cwd=env["PROJECT_DIR"], stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return "0.0.0-dev"
    if out.startswith("v"):
        return out[1:]
    return "0.0.0-g" + out  # no version tag yet, only a commit hash


version = os.environ.get("FW_VERSION", "").strip().lstrip("v") or git_version()
print("Firmware version:", version)
env.Append(CPPDEFINES=[("FW_VERSION", env.StringifyMacro(version))])  # noqa: F821

# Public key for internet updates: keys/fw-signing-pub.pem -> <build>/gen/fw_pubkey.h
# (the same file CI uses to verify the release signature).
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "gen")  # noqa: F821
os.makedirs(gen_dir, exist_ok=True)
with open(os.path.join(env["PROJECT_DIR"], "keys", "fw-signing-pub.pem")) as f:  # noqa: F821
    pem = f.read().strip() + "\n"
header = ("#pragma once\n// generated by scripts/prebuild.py\n"
          "static const char FW_PUBKEY_PEM[] = " +
          "".join('"%s\\n"\n' % line for line in pem.splitlines()) + ";\n")
path = os.path.join(gen_dir, "fw_pubkey.h")
if not os.path.exists(path) or open(path).read() != header:
    with open(path, "w") as f:
        f.write(header)
env.Append(CPPPATH=[gen_dir])  # noqa: F821
